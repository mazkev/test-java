-- 1. Tabel Pengguna (Users: Pembeli & Penjual)
CREATE TABLE users (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255),
    role VARCHAR(50) NOT NULL
);

-- 2. Tabel Produk (Products)
CREATE TABLE products (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    price FLOAT NOT NULL,
    stock NUMBER(10) NOT NULL,
    category VARCHAR(255),
    seller_id NUMBER(19) REFERENCES users(id),
    version NUMBER(19) DEFAULT 0
);

-- 3. Tabel Pesanan (Orders - Header)
CREATE TABLE orders (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id NUMBER(19) REFERENCES users(id),
    total_amount FLOAT,
    order_date TIMESTAMP,
    status VARCHAR(50)
);

-- 4. Tabel Detail Item Pesanan (Order Items)
CREATE TABLE order_items (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER(19) REFERENCES orders(id),
    product_id NUMBER(19),
    product_name VARCHAR(255),
    price FLOAT,
    quantity NUMBER(10),
    subtotal FLOAT
);
